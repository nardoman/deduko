#!/usr/bin/env python3
"""Generate the fixed cases of a Deduko pack.

Usage: gen_cases.py <spec.json> <packDir> [--scratch <dir>]

spec.json: {"id", "version", "cases": [{"id", "difficulty", "seed", "categories"}],
            "settings": [...]}
Each case is generated by DEDUKO.engine.generateFixed(categories, difficulty, seed)
running in headless Chrome (tools/cdp.py), so the result is the same engine the
Kindle runs. Writes <packDir>/pack.js as DEDUKO.addPack(<json>);
The output is deterministic for a given spec.
Chrome profiles go to --scratch (default: $DEDUKO_SCRATCH or the temp dir).
"""
import argparse
import json
import os
import sys
import tempfile

TOOLS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, TOOLS)
from cdp import Chrome, file_url  # noqa: E402

HARNESS = os.path.join(TOOLS, "harness.html")
CASE_KEYS = ["id", "difficulty", "categories", "solution", "clues", "gen"]


def default_scratch():
    return os.environ.get("DEDUKO_SCRATCH") or os.path.join(tempfile.gettempdir(), "deduko-cdp")


def main():
    ap = argparse.ArgumentParser(description="Generate the fixed cases of a Deduko pack.")
    ap.add_argument("spec")
    ap.add_argument("packdir")
    ap.add_argument("--scratch", default=None)
    a = ap.parse_args()
    with open(a.spec, encoding="utf-8") as f:
        spec = json.load(f)
    for key in ("id", "version", "cases"):
        if key not in spec:
            print("spec: missing '%s'" % key)
            return 1
    cases = []
    with Chrome(a.scratch or default_scratch()) as c:
        c.navigate(file_url(HARNESS))
        for cs in spec["cases"]:
            expr = "JSON.stringify(DEDUKO.engine.generateFixed(%s, %s, %s))" % (
                json.dumps(cs["categories"]), json.dumps(cs["difficulty"]), json.dumps(cs["seed"]))
            out = json.loads(c.eval(expr))
            if out is None:
                print("case %s: generation failed (bad categories or shape?)" % cs.get("id"))
                return 1
            out["id"] = cs["id"]
            case = {k: out[k] for k in CASE_KEYS}
            err = c.eval("DEDUKO.engine.validateCase(%s)" % json.dumps(case))
            if err:
                print("case %s: generated case is invalid: %s" % (cs["id"], err))
                return 1
            cases.append(case)
            print("case %s: difficulty %d, %d clues" % (cs["id"], cs["difficulty"], len(case["clues"])))
    pack = {"format": 1, "id": spec["id"], "version": spec["version"], "cases": cases,
            "settings": spec.get("settings", [])}
    os.makedirs(a.packdir, exist_ok=True)
    path = os.path.join(a.packdir, "pack.js")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("DEDUKO.addPack(" + json.dumps(pack, ensure_ascii=False, indent=1) + ");\n")
    print("wrote " + path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
